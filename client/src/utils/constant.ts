/**
 * HTTP状态码常量定义
 * 用于统一管理系统的HTTP响应状态码
 * 状态码分为几个区间：
 * - 2xxx: 成功状态码
 * - 4xxx: 用户相关错误状态码
 * - 6xxx: 文件相关错误状态码
 */
export const HttpStatus = {
    /**
     * 请求成功状态码
     * 表示请求已成功处理，返回期望的数据
     * 对应HTTP标准状态码200
     */
    SUCCESS: 200,

    /**
     * 用户不存在错误状态码
     * 当系统尝试查找或操作一个不存在的用户时返回
     * 通常用于登录、用户信息查询等场景
     * 状态码: 4002
     */
    USER_NOT_EXIT: 4002,

    /**
     * 用户已存在错误状态码
     * 当尝试创建一个已经存在的用户时返回
     * 通常用于用户注册场景
     * 状态码: 4003
     */
    USER_EXIST: 4003,

    /**
     * 文件已存在错误状态码
     * 当尝试上传或创建一个已经存在的文件时返回
     * 通常用于文件上传、文件操作等场景
     * 状态码: 6001
     */
    FILE_EXIST: 6001,

    /**
     * 所有文件块已上传状态码
     * 表示文件分片上传已完成，所有文件块都已成功上传
     * 用于文件分片上传的完成状态确认
     * 状态码: 6002
     */
    ALL_CHUNK_UPLOAD: 6002,
}